# Recreate the exact vectorizer configuration used during your best run
tfidf_rag = TfidfVectorizer(
    max_features=30000,
    min_df=3,
    stop_words='english',
    ngram_range=(1, 2),
    sublinear_tf=True
)
# Build the index matrix
X_rag = tfidf_rag.fit_transform(df['combined_text'])
print(f"Search index ready with shape: {X_rag.shape}\n")


# 2. Define the Retriever using the correct local variables
def tfidf_retriever(query, top_k=3):
    """Transforms a user query and returns the top_k most relevant paper rows."""
    # Convert query into the exact same TF-IDF space
    query_vec = tfidf_rag.transform([query.lower()])

    # Calculate cosine similarity against the search matrix
    similarities = cosine_similarity(query_vec, X_rag).flatten()

    # Get the top K highest similarity indices
    top_indices = np.argsort(similarities)[-top_k:][::-1]

    return df.iloc[top_indices], similarities[top_indices]


# 3. Define the RAG Generation Function
def run_rag_pipeline(query):
    # Phase 1: Retrieve context
    retrieved_docs, scores = tfidf_retriever(query, top_k=2)

    context = ""
    for i, (_, row) in enumerate(retrieved_docs.iterrows()):
        context += f"--- Document {i+1} (Title: {row['title']}) ---\n"
        context += f"Abstract: {row['abstract']}\n\n"

    # Phase 2: Construct Augmented Prompt
    rag_prompt = f"""You are an advanced academic research assistant. Answer the user query using ONLY the provided verified research context below.

If the answer cannot be found in the context, say "I cannot find sufficient evidence in the dataset." Do not make things up.

[VERIFIED CONTEXT]
{context}

[USER QUERY]
{query}

Answer:"""

    # Phase 3: Generate grounded response using the LLM
    outputs = pipe(
        rag_prompt,
        max_new_tokens=100,
        temperature=0.1,
        do_sample=False,
        return_full_text=False
    )

    return outputs[0]['generated_text'].strip(), retrieved_docs

